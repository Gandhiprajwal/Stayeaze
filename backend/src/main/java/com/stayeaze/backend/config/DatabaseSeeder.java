package com.stayeaze.backend.config;

import com.stayeaze.backend.models.*;
import com.stayeaze.backend.repository.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.CommandLineRunner;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.HashSet;
import java.util.Optional;
import java.util.Set;
import java.util.UUID;

@Component
public class DatabaseSeeder implements CommandLineRunner {

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Autowired
    private OrganizationRepository organizationRepository;

    @Autowired
    private RoleRepository roleRepository;

    @Autowired
    private UserRepository userRepository;

    @Autowired
    private PropertyRepository propertyRepository;

    @Autowired
    private CheckInRepository checkInRepository;

    @Autowired
    private CheckOutRepository checkOutRepository;

    @Autowired
    private MaintenanceRepository maintenanceRepository;

    @Autowired
    private PasswordEncoder encoder;

    @Override
    @Transactional
    public void run(String... args) throws Exception {
        // Drop the check constraint generated by EnumType.STRING mapping on roles table
        try {
            jdbcTemplate.execute("ALTER TABLE roles DROP CONSTRAINT IF EXISTS roles_name_check");
        } catch (Exception e) {
            // ignore if database is different or constraint does not exist
        }

        // 1. Seed Core Roles
        seedRoleIfNotFound(ERole.SUPER_ADMIN, "[\"ALL\"]");
        seedRoleIfNotFound(ERole.OWNER, "[\"ALL\"]");
        seedRoleIfNotFound(ERole.PROPERTY_MANAGER, "[\"PROPERTY_WRITE\", \"PROPERTY_READ\"]");
        seedRoleIfNotFound(ERole.RECEPTIONIST, "[\"TENANT_WRITE\", \"TENANT_READ\"]");
        seedRoleIfNotFound(ERole.ACCOUNTANT, "[\"BILLING_WRITE\", \"BILLING_READ\"]");
        seedRoleIfNotFound(ERole.SECURITY_GUARD, "[\"SECURITY_WRITE\", \"SECURITY_READ\"]");
        seedRoleIfNotFound(ERole.STAFF, "[\"SUPPORT_WRITE\", \"SUPPORT_READ\"]");
        seedRoleIfNotFound(ERole.TENANT, "[\"COMPLAINT_WRITE\"]");

        // 2. Seed Super Admin User if none exists
        Optional<Role> superAdminRoleOpt = roleRepository.findByName(ERole.SUPER_ADMIN);
        if (superAdminRoleOpt.isPresent()) {
            Role superAdminRole = superAdminRoleOpt.get();
            long count = userRepository.findAll().stream()
                    .filter(u -> u.getRoles().contains(superAdminRole))
                    .count();

            if (count == 0) {
                // Ensure system organization exists
                Organization systemOrg = organizationRepository.findBySubdomain("system")
                        .orElseGet(() -> {
                            Organization org = new Organization("StayEaze SaaS System", "system");
                            return organizationRepository.save(org);
                        });

                // Create default Super Admin user
                User admin = new User(
                        systemOrg,
                        "admin@stayeaze.com",
                        encoder.encode("admin123"),
                        "0000000000"
                );

                Set<Role> roles = new HashSet<>();
                roles.add(superAdminRole);
                admin.setRoles(roles);

                userRepository.save(admin);
                System.out.println("==================================================");
                System.out.println("🟢 SEEDING: Default Super Admin User Created!");
                System.out.println("   Username / Email: admin@stayeaze.com");
                System.out.println("   Password:         admin123");
                System.out.println("==================================================");
            }
        }

    }

    private void seedRoleIfNotFound(ERole roleName, String permissions) {
        if (!roleRepository.findByName(roleName).isPresent()) {
            Role role = new Role(roleName, permissions);
            roleRepository.save(role);
        }
    }
}
